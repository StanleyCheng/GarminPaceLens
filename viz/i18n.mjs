export function t(input, values = {}) {
  if (input && typeof input === "object" && "source" in input) return t(input.source, input.values);
  const source = String(input ?? "");
  const template = language === "zh-HK" ? TRANSLATIONS[source] ?? source : source;
  // Match only named fields. Plotly's %{x} and %{customdata} are its own tokens.
  return template.replace(/(?<!%)\{([a-zA-Z]\w*)\}/g, (match, key) => {
    const value = values[key];
    return value === undefined ? match : value && typeof value === "object" && "source" in value ? t(value) : String(value);
  });
}

function bind(node, property, input) {
  if (!bindings.has(node)) bindings.set(node, new Map());
  bindings.get(node).set(property, input);
  if (property === "textContent" || property === "nodeValue") node[property] = t(input);
  else node.setAttribute(property, t(input));
}

export const setText = (node, input) => bind(node, "textContent", input);
export const setLabel = (node, attribute, input) => bind(node, attribute, input);
export function onLanguageChange(listener) { listeners.add(listener); return () => listeners.delete(listener); }

export function setLanguage(next) {
  if (!["en", "zh-HK"].includes(next) || next === language) return;
  language = next;
  try { globalThis.window?.localStorage?.setItem(STORAGE_KEY, language); } catch { /* Keep the live toggle working. */ }
  if (typeof document !== "undefined") document.documentElement.lang = language;
  for (const [node, properties] of bindings) {
    if (!node.isConnected) { bindings.delete(node); continue; }
    for (const [property, input] of properties) bind(node, property, input);
  }
  listeners.forEach((listener) => listener());
}

export function errorMessage(error) {
  const source = String(error?.message || error || "");
  return message(Object.hasOwn(TRANSLATIONS, source) ? source : "Could not complete this request. Please try again.");
}

// Bind only the initial authored document, before accounts or activity data load.
// Dynamic copy uses setText/setLabel explicitly. No observer scans user data.
export function initLanguage() {
  document.documentElement.lang = language;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (node.parentElement.closest("script, style, textarea")) continue;
    const source = node.nodeValue.trim();
    if (Object.hasOwn(TRANSLATIONS, source)) {
      const spaceBefore = node.nodeValue.match(/^\s*/)[0];
      const spaceAfter = node.nodeValue.match(/\s*$/)[0];
      bind(node, "nodeValue", message("{before}{copy}{after}", { before: spaceBefore, copy: message(source), after: spaceAfter }));
    }
  }
  document.querySelectorAll("[aria-label], [title], [placeholder], [data-tooltip], meta[name='description']").forEach((node) => {
    for (const attribute of ["aria-label", "title", "placeholder", "data-tooltip", "content"]) {
      const source = node.getAttribute(attribute);
      if (Object.hasOwn(TRANSLATIONS, source)) setLabel(node, attribute, source);
    }
  });
  const button = document.getElementById("language-toggle");
  function updateButton() {
    const text = document.createElement("span");
    text.textContent = language === "en" ? "繁中" : "English";
    text.lang = language === "en" ? "zh-HK" : "en";
    button.replaceChildren(text);
    button.lang = language;
    const label = t(language === "en" ? "Switch to Traditional Chinese" : "Switch to English");
    button.setAttribute("aria-label", label);
    button.title = label;
  }
  button.addEventListener("click", () => setLanguage(language === "en" ? "zh-HK" : "en"));
  onLanguageChange(updateButton);
  updateButton();
  // Native validation messages otherwise follow the browser UI language.
  const fields = [...document.querySelectorAll("input:not([type='file']), textarea")];
  function validate(field) {
    field.setCustomValidity("");
    if (language === "en") return;
    const validity = field.validity;
    let feedback = "";
    if (validity.valueMissing) feedback = t("Enter a value for this field.");
    else if (validity.typeMismatch) feedback = t("Enter a valid email address.");
    else if (validity.patternMismatch) feedback = t("Use the format shown for this field.");
    else if (validity.tooShort) feedback = t("Use at least {count} characters.", { count: field.minLength });
    else if (validity.tooLong) feedback = t("Use no more than {count} characters.", { count: field.maxLength });
    field.setCustomValidity(feedback);
  }
  fields.forEach((field) => {
    field.addEventListener("invalid", () => validate(field));
    field.addEventListener("input", () => field.setCustomValidity(""));
  });
  onLanguageChange(() => fields.forEach((field) => field.setCustomValidity("")));
}

